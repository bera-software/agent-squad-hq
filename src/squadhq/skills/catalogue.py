"""Generate ``docs/skills/CATALOGUE.md`` from the manifests."""
from __future__ import annotations

from collections import Counter

from squadhq.skills.loader import Skill
from squadhq.skills.schema import PHASES, TIERS, trigger_summary

PHASE_TITLES = {
    "plan": "Product and planning", "design": "Design and architecture", "build": "Build",
    "verify": "Verify and quality", "release": "Release", "operate": "Operations",
    "business": "Business departments", "platform": "Platform (Agent Squad HQ itself)",
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _outputs(skill: Skill) -> str:
    parts = []
    for o in skill.outputs:
        typ = o.get("type")
        if typ == "artifact":
            parts.append(f"`{o.get('path')}`")
        elif typ == "label":
            parts.append("label " + ", ".join(f"`{x}`" for x in o.get("labels") or []))
        else:
            parts.append(str(typ))
    return ", ".join(parts)


def _gate(skill: Skill) -> str:
    if not skill.gate:
        return ""
    bits = []
    if skill.gate.get("check"):
        bits.append(f"check `{skill.gate['check']}`")
    if skill.gate.get("blocking_label"):
        bits.append(f"blocks on `{skill.gate['blocking_label']}`")
    if skill.gate.get("verdict"):
        bits.append(f"verdict `{skill.gate['verdict']}`")
    return "; ".join(bits)


def render_markdown(skills: dict[str, Skill]) -> str:
    phases = Counter(s.phase for s in skills.values())
    tiers = Counter(s.tier for s in skills.values())
    lines = [
        "# Skill catalogue",
        "",
        "<!-- Generated by `python -m squadhq.skills catalogue-md`. Do not edit by hand. -->",
        "",
        f"{len(skills)} skills: "
        + ", ".join(f"{tiers.get(t, 0)} {t}" for t in TIERS)
        + f". {sum(1 for s in skills.values() if s.legacy)} existed before the catalogue (★); "
        + f"{sum(1 for s in skills.values() if s.deterministic)} are deterministic (no model).",
        "",
        "Enable or disable skills in `squadhq.yml` under `skills:` (or `agents:`), globally or per project. "
        "See [authoring-skills.md](authoring-skills.md) to add one and [evals.md](evals.md) for testing.",
        "",
        "| Phase | Skills |",
        "|---|---|",
    ]
    for phase in PHASES:
        if phases.get(phase):
            lines.append(f"| [{PHASE_TITLES[phase]}](#{phase}) | {phases[phase]} |")
    lines.append("")
    for phase in PHASES:
        group = sorted((s for s in skills.values() if s.phase == phase), key=lambda s: s.id)
        if not group:
            continue
        lines += [f'<a id="{phase}"></a>', f"## {PHASE_TITLES[phase]}", "",
                  "| Skill | Tier | Default | Trigger | Tools | Model | Outputs | Gate |",
                  "|---|---|---|---|---|---|---|---|"]
        for s in group:
            star = " ★" if s.legacy else ""
            trig = "<br>".join(_cell(trigger_summary(t)) for t in s.triggers)
            lines.append(
                f"| **{_cell(s.name)}**{star}<br>`{s.id}` | {s.tier} | {'on' if s.default_enabled else 'off'} "
                f"| {trig} | {s.tool_profile} | {s.model_tier} | {_cell(_outputs(s))} | {_cell(_gate(s))} |")
        lines.append("")
        for s in group:
            req = f" Requires: {', '.join(f'`{r}`' for r in s.requires)}." if s.requires else ""
            lines.append(f"- **`{s.id}`**: {_cell(s.summary)}{req}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
